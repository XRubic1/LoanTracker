-- Helper: can the current user see a client_insurance row?
-- Uses dynamic SQL so team_members / linked_owner_ids are only queried when they exist.
CREATE OR REPLACE FUNCTION public.brokersnapshot_can_access_client_insurance(p_client_insurance_id BIGINT)
RETURNS BOOLEAN
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  allowed BOOLEAN;
BEGIN
  SELECT EXISTS (
    SELECT 1
    FROM public.client_insurance ci
    WHERE ci.id = p_client_insurance_id
      AND (ci.owner_id = auth.uid() OR ci.owner_id IS NULL)
  ) INTO allowed;
  IF allowed THEN
    RETURN true;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'public' AND table_name = 'team_members'
  ) THEN
    EXECUTE $sql$
      SELECT EXISTS (
        SELECT 1
        FROM public.client_insurance ci
        WHERE ci.id = $1
          AND ci.owner_id IN (
            SELECT tm.owner_id FROM public.team_members tm WHERE tm.member_id = auth.uid()
          )
      )
    $sql$ INTO allowed USING p_client_insurance_id;
    IF allowed THEN
      RETURN true;
    END IF;
  END IF;

  IF EXISTS (
    SELECT 1 FROM pg_proc p
    JOIN pg_namespace n ON p.pronamespace = n.oid
    WHERE n.nspname = 'public' AND p.proname = 'linked_owner_ids'
  ) THEN
    EXECUTE $sql$
      SELECT EXISTS (
        SELECT 1
        FROM public.client_insurance ci
        WHERE ci.id = $1
          AND ci.owner_id IN (SELECT public.linked_owner_ids())
      )
    $sql$ INTO allowed USING p_client_insurance_id;
    IF allowed THEN
      RETURN true;
    END IF;
  END IF;

  RETURN false;
END;
$$;

DROP POLICY IF EXISTS "brokersnapshot_sync_runs_select" ON public.brokersnapshot_sync_runs;
CREATE POLICY "brokersnapshot_sync_runs_select" ON public.brokersnapshot_sync_runs
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "brokersnapshot_api_logs_select" ON public.brokersnapshot_api_logs;
CREATE POLICY "brokersnapshot_api_logs_select" ON public.brokersnapshot_api_logs
  FOR SELECT TO authenticated
  USING (
    client_insurance_id IS NULL
    OR owner_id = auth.uid()
    OR public.brokersnapshot_can_access_client_insurance(client_insurance_id)
  );

DROP POLICY IF EXISTS "brokersnapshot_suggestions_select" ON public.brokersnapshot_cancellation_suggestions;
CREATE POLICY "brokersnapshot_suggestions_select" ON public.brokersnapshot_cancellation_suggestions
  FOR SELECT TO authenticated
  USING (
    owner_id = auth.uid()
    OR public.brokersnapshot_can_access_client_insurance(client_insurance_id)
  );

DROP POLICY IF EXISTS "brokersnapshot_suggestions_update" ON public.brokersnapshot_cancellation_suggestions;
CREATE POLICY "brokersnapshot_suggestions_update" ON public.brokersnapshot_cancellation_suggestions
  FOR UPDATE TO authenticated
  USING (public.brokersnapshot_can_access_client_insurance(client_insurance_id))
  WITH CHECK (public.brokersnapshot_can_access_client_insurance(client_insurance_id));

