-- BrokerSnapshot API monitoring: sync runs, per-client API logs, cancellation suggestions.
-- Requires auth.users (Supabase default). Bootstraps client_insurance if migration 008 was not run yet.

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

