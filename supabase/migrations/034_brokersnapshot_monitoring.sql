-- One row per daily or manual sync run.
CREATE TABLE IF NOT EXISTS public.brokersnapshot_sync_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status TEXT NOT NULL DEFAULT 'running'
    CHECK (status IN ('running', 'success', 'partial', 'failed')),
  trigger_source TEXT NOT NULL DEFAULT 'cron'
    CHECK (trigger_source IN ('cron', 'manual')),
  clients_checked INTEGER NOT NULL DEFAULT 0,
  cancellations_found INTEGER NOT NULL DEFAULT 0,
  errors_count INTEGER NOT NULL DEFAULT 0,
  error_summary TEXT,
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  finished_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_brokersnapshot_sync_runs_started_at
  ON public.brokersnapshot_sync_runs (started_at DESC);

-- One row per API call during a sync run.
CREATE TABLE IF NOT EXISTS public.brokersnapshot_api_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sync_run_id BIGINT NOT NULL REFERENCES public.brokersnapshot_sync_runs(id) ON DELETE CASCADE,
  client_insurance_id BIGINT REFERENCES public.client_insurance(id) ON DELETE SET NULL,
  owner_id UUID,
  client_name TEXT,
  mc TEXT,
  dot TEXT,
  request_path TEXT,
  http_status INTEGER,
  success BOOLEAN NOT NULL DEFAULT false,
  error_message TEXT,
  response_summary JSONB,
  cancellation_detected BOOLEAN NOT NULL DEFAULT false,
  cancellation_date DATE,
  duration_ms INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_brokersnapshot_api_logs_sync_run_id
  ON public.brokersnapshot_api_logs (sync_run_id);
CREATE INDEX IF NOT EXISTS idx_brokersnapshot_api_logs_created_at
  ON public.brokersnapshot_api_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_brokersnapshot_api_logs_client_insurance_id
  ON public.brokersnapshot_api_logs (client_insurance_id);

-- Pending cancellation suggestions requiring manual approval.
CREATE TABLE IF NOT EXISTS public.brokersnapshot_cancellation_suggestions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sync_run_id BIGINT REFERENCES public.brokersnapshot_sync_runs(id) ON DELETE SET NULL,
  client_insurance_id BIGINT NOT NULL REFERENCES public.client_insurance(id) ON DELETE CASCADE,
  owner_id UUID,
  client_name TEXT,
  mc TEXT,
  suggested_cancellation_date DATE NOT NULL,
  suggested_dot TEXT,
  policy_number TEXT,
  insurance_company TEXT,
  source_data JSONB,
  review_status TEXT NOT NULL DEFAULT 'pending'
    CHECK (review_status IN ('pending', 'approved', 'rejected', 'superseded')),
  reviewed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  review_note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_brokersnapshot_suggestions_review_status
  ON public.brokersnapshot_cancellation_suggestions (review_status);
CREATE INDEX IF NOT EXISTS idx_brokersnapshot_suggestions_client_insurance_id
  ON public.brokersnapshot_cancellation_suggestions (client_insurance_id);
CREATE INDEX IF NOT EXISTS idx_brokersnapshot_suggestions_created_at
  ON public.brokersnapshot_cancellation_suggestions (created_at DESC);

