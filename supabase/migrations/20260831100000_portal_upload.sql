-- Upload tab: saved logins for client portals (e.g. TruFunding) and a log of what was uploaded.
-- Passwords are encrypted by the portal-upload edge function (AES-GCM, key in the PORTAL_CRED_KEY secret).
-- RLS is on with no policies: the browser can never read these tables; only the edge function (service role) can.

CREATE TABLE IF NOT EXISTS public.portal_upload_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  label TEXT NOT NULL,
  portal_url TEXT NOT NULL DEFAULT 'https://clients.trufunding.net',
  username TEXT NOT NULL,
  password_enc TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_portal_upload_accounts_owner ON public.portal_upload_accounts (owner_id);

CREATE TABLE IF NOT EXISTS public.portal_upload_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  account_id BIGINT REFERENCES public.portal_upload_accounts (id) ON DELETE SET NULL,
  account_label TEXT NOT NULL,
  batch_no TEXT,
  file_names TEXT[] NOT NULL DEFAULT '{}',
  processed BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL,
  message TEXT,
  uploaded_by TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_portal_upload_log_owner ON public.portal_upload_log (owner_id, created_at DESC);

ALTER TABLE public.portal_upload_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.portal_upload_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.portal_upload_accounts FROM anon, authenticated;
REVOKE ALL ON public.portal_upload_log FROM anon, authenticated;
