-- Revised invoices created through the Upload tab. We keep a record of every one so that only
-- invoices created here can be processed from here. No policies: only the edge function can read or write.

CREATE TABLE IF NOT EXISTS public.portal_revised_invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  account_id BIGINT REFERENCES public.portal_upload_accounts (id) ON DELETE SET NULL,
  account_label TEXT NOT NULL,
  /** The portal's id for the unprocessed invoice (InvoiceInputId). */
  invoice_input_id BIGINT NOT NULL,
  original_invoice_key BIGINT NOT NULL,
  original_invoice_no TEXT NOT NULL,
  new_invoice_no TEXT NOT NULL,
  po_no TEXT NOT NULL,
  broker TEXT NOT NULL,
  amount NUMERIC(14, 2) NOT NULL,
  status TEXT NOT NULL DEFAULT 'created' CHECK (status IN ('created', 'processed', 'removed')),
  created_by TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_by TEXT,
  finished_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_portal_revised_owner ON public.portal_revised_invoices (owner_id, status, created_at DESC);

-- One open revised invoice per original invoice, so it cannot be created twice by accident.
CREATE UNIQUE INDEX IF NOT EXISTS idx_portal_revised_open_original
  ON public.portal_revised_invoices (account_id, original_invoice_key)
  WHERE status = 'created';

ALTER TABLE public.portal_revised_invoices ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.portal_revised_invoices FROM anon, authenticated;
