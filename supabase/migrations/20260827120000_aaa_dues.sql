-- Weekly AAA payments that are owed: company, payee, amount, week, and the deductions (partial payments)
-- posted against them. Closing one creates the normal aaa_payments record.
CREATE TABLE IF NOT EXISTS public.aaa_dues (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  client TEXT NOT NULL,
  payee TEXT NOT NULL DEFAULT 'AAA Lease',
  amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
  week_start DATE NOT NULL,
  deductions JSONB NOT NULL DEFAULT '[]'::jsonb,
  closed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT aaa_dues_payee_check CHECK (
    payee IN ('AAA Lease', 'AAA Mega Fuel', 'AAA Equipment', 'BJK Fuel')
  )
);

CREATE INDEX IF NOT EXISTS idx_aaa_dues_owner_id ON public.aaa_dues (owner_id);
CREATE INDEX IF NOT EXISTS idx_aaa_dues_open ON public.aaa_dues (week_start) WHERE closed_at IS NULL;

ALTER TABLE public.aaa_dues ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "aaa_dues_select" ON public.aaa_dues;
CREATE POLICY "aaa_dues_select" ON public.aaa_dues FOR SELECT
  USING (
    owner_id = auth.uid()
    OR owner_id IN (SELECT owner_id FROM public.team_members WHERE member_id = auth.uid())
    OR owner_id IS NULL
  );

DROP POLICY IF EXISTS "aaa_dues_insert" ON public.aaa_dues;
CREATE POLICY "aaa_dues_insert" ON public.aaa_dues FOR INSERT
  WITH CHECK (
    owner_id = auth.uid()
    OR owner_id IN (SELECT owner_id FROM public.team_members WHERE member_id = auth.uid())
    OR owner_id IS NULL
  );

DROP POLICY IF EXISTS "aaa_dues_update" ON public.aaa_dues;
CREATE POLICY "aaa_dues_update" ON public.aaa_dues FOR UPDATE
  USING (
    owner_id = auth.uid()
    OR owner_id IN (SELECT owner_id FROM public.team_members WHERE member_id = auth.uid())
    OR owner_id IS NULL
  )
  WITH CHECK (true);

DROP POLICY IF EXISTS "aaa_dues_delete" ON public.aaa_dues;
CREATE POLICY "aaa_dues_delete" ON public.aaa_dues FOR DELETE
  USING (
    owner_id = auth.uid()
    OR owner_id IN (SELECT owner_id FROM public.team_members WHERE member_id = auth.uid())
    OR owner_id IS NULL
  );

DO $$
BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE public.aaa_dues;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
ALTER TABLE public.aaa_dues REPLICA IDENTITY FULL;

-- A closed payment keeps the per-day deductions and the week it was for.
ALTER TABLE public.aaa_payments
  ADD COLUMN IF NOT EXISTS deductions JSONB NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS week_start DATE;
